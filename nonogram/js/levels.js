// Utility: Calculate row and column clues from a 2D binary grid
function generateCluesFromGrid(grid) {
    const rows = grid.length;
    const cols = grid[0].length;

    const rowClues = [];
    for (let r = 0; r < rows; r++) {
        const line = [];
        let count = 0;
        for (let c = 0; c < cols; c++) {
            if (grid[r][c] === 1) {
                count++;
            } else if (count > 0) {
                line.push(count);
                count = 0;
            }
        }
        if (count > 0) line.push(count);
        rowClues.push(line.length > 0 ? line : [0]);
    }

    const colClues = [];
    for (let c = 0; c < cols; c++) {
        const line = [];
        let count = 0;
        for (let r = 0; r < rows; r++) {
            if (grid[r][c] === 1) {
                count++;
            } else if (count > 0) {
                line.push(count);
                count = 0;
            }
        }
        if (count > 0) line.push(count);
        colClues.push(line.length > 0 ? line : [0]);
    }

    return { rowClues, colClues };
}

